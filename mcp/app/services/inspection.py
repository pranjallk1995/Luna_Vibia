"""Read what an audio file says about itself: format, tags, and AI provenance."""

from __future__ import annotations

import re
from typing import Any

from app.core.config import AppConfig
from app.integrations.audio import AudioProbe

Row = dict[str, Any]


class TrackInspector:
    """Describe an audio file: container, stream, embedded tags, and AI signals.

    AI music generators commonly write their name into the file's tags (title,
    comment, encoder, or a description such as "made with Suno"). Those mentions
    are reported as ai_signals; missing ones do not prove a track is human-made,
    since re-encoding or editing drops tags.
    """

    GENERATORS = re.compile(
        r"\b(suno|udio|musicgen|audiocraft|stable audio|lyria|riffusion|aiva|mubert|"
        r"soundraw|boomy|beatoven|elevenlabs|ai[- ]generated|generated by ai)\b",
        re.IGNORECASE,
    )
    # Tags whose text is worth showing; others (encoder settings, IDs) are noise.
    TEXT_TAGS = ("title", "artist", "album", "album_artist", "genre", "date", "comment", "description",
                 "lyrics", "composer", "encoder", "encoded_by", "copyright", "publisher", "software")

    def __init__(self, probe: AudioProbe | None = None) -> None:
        self.probe = probe or AudioProbe()

    @staticmethod
    def _text(value: Any) -> str | None:
        if not isinstance(value, (str, int, float)):
            return None
        text = str(value).strip().strip("\0")
        if not text:
            return None
        limit = AppConfig.INSPECTION_MAX_TEXT_CHARS
        return text[:limit] + "…" if len(text) > limit else text

    def inspect(self, data: bytes) -> Row:
        probed = self.probe.probe(data)
        tags = {key: text for key, value in probed["tags"].items() if (text := self._text(value))}
        shown = {key: tags[key] for key in self.TEXT_TAGS if key in tags}
        signals = sorted(
            {f"{key}: {match.group(0)}" for key, text in tags.items() if (match := self.GENERATORS.search(text))}
        )
        generator = next((self.GENERATORS.search(text).group(0) for text in tags.values() if self.GENERATORS.search(text)), None)
        return {
            "file": {
                "format": probed["format"],
                "codec": probed["codec"],
                "duration_seconds": probed["duration_seconds"],
                "sample_rate": probed["sample_rate"],
                "channels": probed["channels"],
                "bitrate": probed["bitrate"],
            },
            # Not "tags": that is the track's own search tags when merged with its record.
            "embedded_tags": shown,
            "ai_generated": bool(signals),
            "ai_signals": signals,
            "generator": generator,
        }

    @staticmethod
    def summarize(inspected: Row) -> Row:
        """Reduce an inspection to the fields worth sending for many tracks at once."""
        file, tags = inspected["file"], inspected["embedded_tags"]
        summary = {
            "format": file["format"],
            "duration_seconds": file["duration_seconds"],
            "ai_generated": inspected["ai_generated"],
            "ai_signals": inspected["ai_signals"] or None,
            "generator": inspected["generator"],
            "title": tags.get("title"),
            "artist": tags.get("artist"),
        }
        return {key: value for key, value in summary.items() if value is not None}

    def is_ai_generated(self, data: bytes) -> bool:
        try:
            return self.inspect(data)["ai_generated"]
        except ValueError:
            return False
